from pathlib import Path
import json, textwrap

P = Path(__file__).resolve().parents[1]
changes = []

def add(file, label, menu_index, key, body):
    path = P / 'game' / (file + '.rpy')
    lines = path.read_text(encoding='utf-8').splitlines(True)
    start = next(i for i, line in enumerate(lines) if line.startswith('label ' + label + ':'))
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith('label ')), len(lines))
    menus = [i for i in range(start, end) if lines[i].strip() == 'menu:']
    n = menus[menu_index]
    indent = len(lines[n]) - len(lines[n].lstrip())
    stop = n + 1
    while stop < len(lines) and (not lines[stop].strip() or len(lines[stop]) - len(lines[stop].lstrip()) > indent):
        stop += 1
    options = [s.strip() for s in lines[n+1:stop] if len(s)-len(s.lstrip()) == indent+4 and s.lstrip().startswith('"')]
    assert len(options) == 2, (label, options)
    block = textwrap.dedent(body).strip().splitlines()
    block.insert(1, '    $ remember("choice_third_' + key + '")')
    inserted = [' ' * (indent+4) + s + '\n' for s in block]
    lines[stop:stop] = inserted
    path.write_text(''.join(lines), encoding='utf-8')
    changes.append(dict(file=file+'.rpy', label=label, menu_index=menu_index, key=key, old_options=options, new_option=block[0], new_dialogue=block[2:]))

